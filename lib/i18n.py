def localize(key: str) -> dict[str, str]:
    """查詢術語白話名 + 一句話說明；找不到就回原文（不報錯）。"""
    return TERMS.get(key, {'zh': key, 'tip': ''})


def localize_name(key: str) -> str:
    return localize(key)['zh']


def localize_tip(key: str) -> str:
    return localize(key)['tip']